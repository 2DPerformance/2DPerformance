/** อักขระที่ไม่อยู่ในตาราง — เผื่อกว้างไว้ก่อน ดีกว่าเผื่อขาดแล้วป้ายล้น */
export const UNKNOWN_CHAR_EM = 0.75;

/** ความกว้างข้อความเป็นเท่าของความสูงตัวอักษร */
export function textWidthEm(s) {
  let w = 0;
  for (const ch of String(s == null ? '' : s)) {
    const cw = SARABUN_WIDTH_EM[ch];
    w += cw === undefined ? UNKNOWN_CHAR_EM : cw;
  }
  return w;
}

/** ความกว้างข้อความในหน่วยเดียวกับความสูง h ที่ส่งมา */
export const textWidth = (s, h) => textWidthEm(s) * h;
